 await page.waitForFunction(()=>document.documentElement.lang==='en');
 assert.ok(Date.now()-started>=400,'Language should not swap immediately');
 await page.waitForFunction(()=>!document.documentElement.classList.contains('language-changing'));
 assert.equal(await trigger.getAttribute('aria-expanded'),'false');
 console.log('PASS deliberate language transition, custom picker keyboard, Escape and selection');
 await trigger.click();await page.screenshot({path:'docs/validation/polish-language-menu.png'});
