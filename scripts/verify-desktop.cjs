    checks.push('PASS titlebar keyboard order and mobile focused contact uncovered by mini player');
    await page.locator('.mini-toggle').click();assert.equal(await page.locator('.radio-audio').evaluate(audio=>audio.paused),true);
    await page.locator('.mini-toggle').click();await page.waitForFunction(()=>!document.querySelector('.radio-audio').paused);
    await page.locator('.radio-return').click();await page.locator('.radio-floating-player').waitFor({state:'hidden'});
    await page.locator('.radio-skip').last().click();await page.waitForFunction(()=>document.querySelector('.radio-audio').src.endsWith('lofi.mp3')&&!document.querySelector('.radio-audio').paused);
    await page.locator('.radio-audio').evaluate(audio=>audio.dispatchEvent(new Event('ended')));
    await page.waitForFunction(()=>document.querySelector('.radio-audio').src.endsWith('study-and-relax.mp3')&&!document.querySelector('.radio-audio').paused);
