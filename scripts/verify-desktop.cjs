    await page.screenshot({animations:'disabled',path:'docs/validation/desktop-radio-mini.png'});
    await page.locator('.radio-stop').click();await page.locator('.radio-floating-player').waitFor({state:'hidden'});
    assert.equal(await page.locator('.radio-audio').evaluate(audio=>audio.paused),true);
    checks.push('PASS real local audio decoding/playback, volume, next track, repeat, persistent playback, mini pause/resume and close');
